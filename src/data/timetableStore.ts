// 특정 일자가 수업이 없는 날(방학, 공휴일, 주말 등)인지 판단
export interface NonClassDayInfo {
  isNonClass: boolean;
  reason: string;
}

export function checkNonClassDay(dateStr: string): NonClassDayInfo {
  if (!dateStr || dateStr.length !== 8) {
    return { isNonClass: false, reason: '' };
  }

  const y = parseInt(dateStr.substring(0, 4), 10);
  const m = parseInt(dateStr.substring(4, 6), 10);
  const d = parseInt(dateStr.substring(6, 8), 10);
  const dateObj = new Date(y, m - 1, d);
  const dayOfWeek = dateObj.getDay(); // 0: 일요일, 6: 토요일

  // 1. 주말
  if (dayOfWeek === 0) {
    return { isNonClass: true, reason: '일요일 (주말)' };
  }
  if (dayOfWeek === 6) {
    return { isNonClass: true, reason: '토요휴업일 (주말)' };
  }

  // 2. 공휴일 / 기념일
  if (dateStr === '20260101') return { isNonClass: true, reason: '신정 (공휴일)' };
  if (dateStr === '20260301') return { isNonClass: true, reason: '3·1절 (공휴일)' };
  if (dateStr === '20260302') return { isNonClass: true, reason: '대체공휴일' };
  if (dateStr === '20260505') return { isNonClass: true, reason: '어린이날 (공휴일)' };
  if (dateStr === '20260606') return { isNonClass: true, reason: '현충일 (공휴일)' };
  if (dateStr === '20260815') return { isNonClass: true, reason: '광복절 (공휴일)' };
  if (dateStr === '20261003') return { isNonClass: true, reason: '개천절 (공휴일)' };
  if (dateStr === '20261009') return { isNonClass: true, reason: '한글날 (공휴일)' };
  if (dateStr === '20261225') return { isNonClass: true, reason: '성탄절 (공휴일)' };

  // 3. 방학 기간 (겨울방학: 2026-01-10 ~ 2026-02-28, 여름방학: 7월 중순~8월 중순)
  if (dateStr >= '20260110' && dateStr <= '20260228') {
    return { isNonClass: true, reason: '겨울방학' };
  }
  if (dateStr >= '20260720' && dateStr <= '20260820') {
    return { isNonClass: true, reason: '여름방학' };
  }

  return { isNonClass: false, reason: '' };
}

export function getDeptName(grade: number, classNum: number): string {
  if (grade === 1) {
    if (classNum <= 3) return '전기전자과';
    if (classNum <= 5) return 'AI소프트웨어과';
    if (classNum <= 8) return '스마트콘텐츠과';
    return '산업디자인과';
  } else if (grade === 2) {
    if (classNum <= 3) return '전기전자과';
    if (classNum <= 5) return 'AI소프트웨어과';
    if (classNum <= 8) return '스마트콘텐츠과';
    return '산업디자인과';
  } else {
    if (classNum <= 3) return '전기전자과';
    if (classNum <= 5) return '컴퓨터소프트웨어과';
    if (classNum <= 8) return '스마트콘텐츠과';
    return '산업디자인과';
  }
}

/**
 * 특정 일자의 시간표 데이터를 반환 (수업 없는 날은 빈 배열)
 */
export function getTimetableData(params: {
  date: string;
  grade: number;
  classNum?: number;
}): TimetableEntry[] {
  const { date, grade, classNum } = params;
  const nonClass = checkNonClassDay(date);

  // 수업이 없는 날은 빈 배열을 반환하여 안내 화면을 표시
  if (nonClass.isNonClass) {
    return [];
  }

  const y = parseInt(date.substring(0, 4), 10);
  const m = parseInt(date.substring(4, 6), 10);
  const d = parseInt(date.substring(6, 8), 10);
  const dateObj = new Date(y, m - 1, d);
  const dayOfWeek = dateObj.getDay(); // 1:월, 2:화, 3:수, 4:목, 5:금

  if (dayOfWeek < 1 || dayOfWeek > 5) {
    return [];
  }

  const ay = m <= 2 ? String(y - 1) : String(y);
  const sem = (m >= 3 && m <= 7) ? '1' : '2';

  const result: TimetableEntry[] = [];
  const targetClasses = classNum ? [classNum] : Array.from({ length: 10 }, (_, i) => i + 1);

  for (const c of targetClasses) {
    const key = `${grade}-${c}-${dayOfWeek}`;
    const subjects = SCHEDULE_MAP[key];
    const dept = getDeptName(grade, c);

    if (subjects) {
      subjects.forEach((subject, idx) => {
        result.push({
          ay,
          sem,
          date,
          dept,
          grade,
          classNum: c,
          period: idx + 1,
          subject,
        });
      });
    }
  }

  return result;
}

